// ── Menus ─────────────────────────────────────────────────────
export async function seedMenus(categoryTree: { slug: string; nameFa: string; children?: { slug: string; nameFa: string }[] }[]) {
  step('منوها (menus)');
  let mainCount = 0;
  let parentSort = 0;
  for (const cat of categoryTree) {
    const existingParent = await db.menuItem.findFirst({ where: { menuKey: 'main', label: cat.nameFa, parentId: null } });
    const parent = existingParent
      ? existingParent
      : await db.menuItem.create({
          data: { menuKey: 'main', label: cat.nameFa, href: `/category/${cat.slug}`, sortOrder: parentSort, iconKey: `/media/categories/${cat.slug}.webp` },
        });
    mainCount++;
    let childSort = 0;
    for (const child of cat.children ?? []) {
      const existingChild = await db.menuItem.findFirst({ where: { menuKey: 'main', label: child.nameFa, parentId: parent.id } });
      if (!existingChild) {
        await db.menuItem.create({
          data: { menuKey: 'main', label: child.nameFa, href: `/category/${child.slug}`, parentId: parent.id, sortOrder: childSort },
        });
        mainCount++;
      }
      childSort++;
    }
    parentSort++;
  }

  const footer1: { label: string; href: string }[] = [
    { label: 'درباره ما', href: '/page/about' },
    { label: 'تماس با ما', href: '/page/contact' },
    { label: 'سوالات متداول', href: '/page/faq' },
    { label: 'راهنمای خرید', href: '/page/how-to-buy' },
  ];
  const footer2: { label: string; href: string }[] = [
    { label: 'قوانین و مقررات', href: '/page/terms' },
    { label: 'حریم خصوصی', href: '/page/privacy' },
    { label: 'قوانین بازپرداخت', href: '/page/refund-policy' },
    { label: 'راهنمای فعال‌سازی', href: '/page/activation-guides' },
  ];
  let footerCount = 0;
  for (const [menuKey, items] of [['footer-1', footer1], ['footer-2', footer2]] as const) {
    let sortOrder = 0;
    for (const item of items) {
      const existing = await db.menuItem.findFirst({ where: { menuKey, label: item.label } });
      if (!existing) {
        await db.menuItem.create({ data: { menuKey, label: item.label, href: item.href, sortOrder } });
        footerCount++;
      }
      sortOrder++;
    }
  }
  count('menuItems', mainCount + footerCount);
  ok(`${mainCount} آیتم منوی اصلی + ${footerCount} آیتم منوی فوتر`);
}
