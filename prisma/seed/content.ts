export async function seedPages() {
  step('صفحات (pages)');
  for (const p of PAGES) {
    await db.page.upsert({
      where: { slug: p.slug },
      update: { titleFa: p.titleFa, excerptFa: p.excerptFa, contentFa: p.contentFa, showInFooter: p.showInFooter ?? false, sortOrder: p.sortOrder ?? 0 },
      create: {
        slug: p.slug, titleFa: p.titleFa, excerptFa: p.excerptFa, contentFa: p.contentFa,
        status: 'PUBLISHED', showInFooter: p.showInFooter ?? false, sortOrder: p.sortOrder ?? 0,
        seoTitle: `${p.titleFa} | گیفتی‌پی`, seoDescription: p.excerptFa,
      },
    });
    count('pages', 1);
  }
  ok(`${PAGES.length} صفحه`);
}

