export async function seedBlog(adminId: string) {
  step('مقالات وبلاگ (blog posts)');
  let idx = 0;
  for (const post of BLOG_POSTS) {
    const contentFa = post.body.join('\n\n');
    const wordCount = contentFa.split(/\s+/).length;
    await db.blogPost.upsert({
      where: { slug: post.slug },
      update: {
        titleFa: post.titleFa, excerptFa: post.body[0].slice(0, 180) + '…', contentFa,
        categoryFa: post.categoryFa, tags: post.tags, readingMinutes: post.readingMinutes,
      },
      create: {
        slug: post.slug, titleFa: post.titleFa, excerptFa: post.body[0].slice(0, 180) + '…', contentFa,
        coverPath: `/media/blog/${post.slug}.webp`, coverAlt: post.titleFa,
        authorId: adminId, categoryFa: post.categoryFa, tags: post.tags, readingMinutes: post.readingMinutes,
        status: 'PUBLISHED', publishedAt: daysAgo(60 - idx * 3), isDemo: true,
        seoTitle: `${post.titleFa} | وبلاگ گیفتی‌پی`, seoDescription: post.body[0].slice(0, 150),
      },
    });
    count('blogPosts', 1);
    void wordCount;
    idx++;
  }
  ok(`${BLOG_POSTS.length} مقاله وبلاگ`);
}

